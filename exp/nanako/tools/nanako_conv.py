def to_pens (im):
	# RGB image in the original palette -> new pens
	inv = {ORIG_PAL [i]: NEWPEN [i] for i in range (16)}
	im = im.convert ('RGB')
	px = []
	for y in range (im.height):
		row = []
		for x in range (im.width):
			c = im.getpixel ((x, y))
			if c not in inv:
				c = min (ORIG_PAL, key = lambda p: sum ((a - b) ** 2 for a, b in zip (p, c)))
			row.append (inv [c])
		px.append (row)
	return px

def put (scr, px, cx, cy):
	for y, row in enumerate (px):
		for x, p in enumerate (row):
			scr [cy * 8 + y] [cx * 4 + x] = p

def text (scr, s, cx, cy):
	for i, ch in enumerate (s):
		put (scr, ASCII.get (ord (ch), [[9] * 4 for y in range (8)]), cx + i, cy)

