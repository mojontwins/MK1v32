# ----------------------------------------------------------------------------
# ZX placeholders from the CPC ones: a mode 0 pixel is two ZX pixels, and
# each 8x8 cell gets the two most used ZX colours.
# ----------------------------------------------------------------------------

def zxc (rgb):
	# CPC level (0, 1, 2) per channel -> ZX colour 0-7 + bright
	lv = [0 if v < 51 else 1 if v < 171 else 2 for v in rgb]
	mx = max (lv)
	if mx == 0: return 0, 0
	k = (2 if lv [0] >= mx else 0) | (4 if lv [1] >= mx else 0) | (1 if lv [2] >= mx else 0)
	return k, 1 if mx == 2 else 0

ZXRGB = [(0, 0, 0), (0, 0, 205), (205, 0, 0), (205, 0, 205), (0, 205, 0), (0, 205, 205), (205, 205, 0), (205, 205, 205)]
def zxrgb (k, br):
	if br: return tuple (255 if v else 0 for v in ZXRGB [k])
	return ZXRGB [k]

def zx_image (px, wide = True, force = None):
	# pens -> ZX RGB, attribute clash resolved per 8x8 cell. force (x0, x1,
	# paper, ink): cells in that x range get those colours, ink where the
	# pixel isn't black.
	h = len (px)
	w = len (px [0]) * (2 if wide else 1)
	im = Image.new ('RGB', (w, h))
	for cy in range (0, h, 8):
		for cx in range (0, w, 8):
			cnt = {}
			cells = []
			for y in range (cy, min (h, cy + 8)):
				for x in range (cx, cx + 8):
					p = px [y] [x >> 1 if wide else x]
					k, br = zxc (PAL [p])
					cells.append ((x, y, k, br))
					cnt [k] = cnt.get (k, 0) + 1
			if force and force [0] <= cx < force [1]:
				for x, y, k, br in cells:
					im.putpixel ((x, y), force [3] if k else force [2])
				continue
			ks = sorted (cnt, key = lambda k: -cnt [k])
			a = ks [0]
			b = ks [1] if len (ks) > 1 else a
			brs = [br for (x, y, k, br) in cells if k in (a, b) and k]
			br = 1 if brs and sum (brs) * 2 >= len (brs) else 0
			for x, y, k, _ in cells:
				if k not in (a, b):
					# nearest of the two by RGB
					c = PAL [px [y] [x >> 1 if wide else x]]
					k = min ((a, b), key = lambda kk: sum ((u - v) ** 2 for u, v in zip (zxrgb (kk, br), c)))
				im.putpixel ((x, y), zxrgb (k, br))
	return im

def cpc_px (im):
	inv = {PAL [i]: i for i in range (16)}
	return [[inv [im.getpixel ((x, y))] for x in range (im.width)] for y in range (im.height)]


