FZ.save (out ('gfx', 'speccy', 'font.png'))

def scr_rgb (scr):
	im = Image.new ('RGB', (256, 192))
	for y in range (192):
		a = ((y & 0xc0) << 5) | ((y & 7) << 8) | ((y & 0x38) << 2)
		for cx in range (32):
			b = scr [a + cx]
			at = scr [6144 + (y >> 3) * 32 + cx]
			br = (at >> 6) & 1
			ink, pap = zxrgb (at & 7, br), zxrgb ((at >> 3) & 7, br)
			for p in range (8):
				im.putpixel ((cx * 8 + p, y), ink if b & (128 >> p) else pap)
	return im

