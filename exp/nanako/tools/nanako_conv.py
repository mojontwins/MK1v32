# nanako_conv.py - one-shot conversion of Nanako in Classic Japanese Monster
# Castle (CPC, 2009, the source of truth) to MK1 v3.2.
#
# usage: python3 nanako_conv.py         (paths are relative to this script's folder)
#
# Reads ../orig (the CPC sources) and writes:
#   ../dev/levels.h             25 levels (the original's 21 bytes each) + passwords
#   ../enems/enems.ene          26 screens x 3 enemies for ene2h (head, body, puff)
#   ../gfx/cpc/*.png            mode 0 placeholders from the original graphics
#   ../gfx/speccy/*.png         ZX placeholders made from the CPC ones
#
# The loading and ending pictures are NOT converted: the placeholders are
# text-only screens, to be replaced by the reworked graphics.

import os, re
from PIL import Image

H = os.path.dirname (os.path.abspath (__file__))
O = os.path.join (H, '..', 'orig')
D = os.path.join (H, '..')

def rd (*p):
	return open (os.path.join (O, *p), 'rb').read ().decode ('latin-1').replace ('\r', '')

def out (*p):
	f = os.path.join (D, *p)
	os.makedirs (os.path.dirname (f), exist_ok = True)
	return f

