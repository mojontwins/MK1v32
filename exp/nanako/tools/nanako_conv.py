# Sprites: 8 cells per row, each 32x16: graphic (white = ink) + mask (red =
# transparent). Ink where the CPC pixel is bright enough.
# ZX: Nanako and the karakasa are the original ZX ones (charset 67-78 and
# UDGs I-N, see tools/nanako_zxgfx.py); the puff is the CPC one. The mask is
# what can be reached from the edges through empty pixels.
def zx_bits (codes, udg = False):
	# 2 x n chars -> rows of 16 bits
	rows = []
	for r in range (len (codes) // 2):
		a, b = codes [r * 2], codes [r * 2 + 1]
		base = 0xff58 if udg else 0xeb34
		for y in range (8):
			rows.append ((ZXM [base + a * 8 + y] << 8) | ZXM [base + b * 8 + y])
	return rows

def zx_cell (rows):
	# rows (16 of 16 bits) -> (pixels, mask) as sets of (x, y)
	on = {(x, y) for y in range (16) for x in range (16) if rows [y] & (0x8000 >> x)}
	out, st = set (), [(x, y) for x in range (16) for y in (0, 15)] + [(x, y) for y in range (16) for x in (0, 15)]
	while st:
		q = st.pop ()
		if q in out or q in on or not (0 <= q [0] < 16 and 0 <= q [1] < 16): continue
		out.add (q)
		st += [(q [0] + 1, q [1]), (q [0] - 1, q [1]), (q [0], q [1] + 1), (q [0], q [1] - 1)]
	return on, out

