	f.write ('// 3 metatiles wide), 10 fixed objects, 10 boxes (YX, 0 = none; 12x8 metatiles).\n\n')
	f.write ('extern unsigned char levels [0];\nextern unsigned char passwords [0];\n\n#asm\n\t._levels\n')
