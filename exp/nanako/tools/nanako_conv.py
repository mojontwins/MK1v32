# MK1: pen 0 is the sprites' transparent colour. The original used pen 9 as
# the sprite mask and pen 0 for black, so they swap: BLACK_PEN 9.
PEN = list (range (16))
PEN [0], PEN [9] = 9, 0
PAL = [ORIG_PAL [PEN [i]] for i in range (16)] 		# new pen -> RGB
NEWPEN = {PEN [i]: i for i in range (16)} 			# original pen -> new pen

def m0 (b):
	p0 = ((b >> 7) & 1) | (((b >> 3) & 1) << 1) | (((b >> 5) & 1) << 2) | (((b >> 1) & 1) << 3)
	p1 = ((b >> 6) & 1) | (((b >> 2) & 1) << 1) | (((b >> 4) & 1) << 2) | ((b & 1) << 3)
	return p0, p1

def blocks (src, prefix):
	# name -> (w bytes, h, [pens])
	r = {}
	parts = re.split (r'\n\s*\._(\w+)\s*\n', src)
	for k in range (1, len (parts), 2):
		name, body = parts [k], parts [k + 1]
		if not name.startswith (prefix): continue
		bs = [int (x.replace ('$', '0x'), 16) for x in re.findall (r'(\$[0-9A-Fa-f]+|0x[0-9A-Fa-f]+|\b\d+\b)', ' '.join (re.findall (r'defb\s+([^\n;]+)', body)))]
		r [name] = bs
	return r

# Tiles: ._ncjmc_N: defb w, h ; ._ncjmc_N_DATA: defb ...
tsrc = rd ('gfx', 'tiles.h')
T = {}
for name, bs in blocks (tsrc, 'ncjmc_').items ():
	m = re.match (r'ncjmc_(\d+)_DATA$', name)
	if m:
		T [int (m.group (1))] = bs

def tile_px (n):
	# 4x8 pens (original numbering)
	bs = T [n]
	px = []
	for y in range (8):
		row = []
		for x in range (2):
			row += m0 (bs [y * 2 + x])
		px.append (row)
	return px

def sprite_px (src, name, wb, h):
	bs = blocks (src, name) [name + '_DATA'] if (name + '_DATA') in blocks (src, name) else blocks (src, name) [name]
	px = []
	for y in range (h):
		row = []
		for x in range (wb):
			row += m0 (bs [y * wb + x])
		px.append (row)
	return px

def to_new (px, transparent = None):
	return [[0 if (transparent is not None and p == transparent) else NEWPEN [p] for p in row] for row in px]

def img_from (px):
	im = Image.new ('RGB', (len (px [0]), len (px)))
	for y, row in enumerate (px):
		for x, p in enumerate (row):
			im.putpixel ((x, y), PAL [p])
	return im

def meta (tl, tr, bl, br):
	# 2x2 original tiles -> 8x16 (one MK1 CPC tile)
	a, b, c, d = (tile_px (n) for n in (tl, tr, bl, br))
	return to_new ([a [y] + b [y] for y in range (8)] + [c [y] + d [y] for y in range (8)])

