# nanako_beeper.py - one-shot extraction of the title tune of the original ZX
# Spectrum version (2006, CEZ GS) from its snapshot, for the 48K.
#
# usage: python3 nanako_beeper.py       (paths are relative to this script's folder)
#
# Reads ../orig/ncjmc-zx.z80 and writes ../dev/music.h: the original's two
# channel beeper player (at E979-EB30 in the snapshot, disassembled and
# relocated here by hand) and the song (128 notes per channel, EB31 / EBB3).
#
# MK1's interface: musicstart plays from the start until a key is pressed;
# musicresume goes on from where it was.

import os, struct

H = os.path.dirname (os.path.abspath (__file__))
O = os.path.join (H, '..', 'orig')
D = os.path.join (H, '..')

d = open (os.path.join (O, 'ncjmc-zx.z80'), 'rb').read ()
hl = struct.unpack ('<H', d [30:32]) [0]
p7 = d [35]

def unrle (b):
	o, i = bytearray (), 0
	while i < len (b):
		if b [i] == 0xed and i + 1 < len (b) and b [i + 1] == 0xed:
			o += bytes ([b [i + 3]]) * b [i + 2]; i += 4
		else:
			o.append (b [i]); i += 1
	return o

banks, i = {}, 32 + hl
while i < len (d):
	l, pg = struct.unpack ('<HB', d [i:i + 3])
	n = 16384 if l == 0xffff else l
	banks [pg - 3] = bytes (d [i + 3:i + 3 + n]) if l == 0xffff else bytes (unrle (d [i + 3:i + 3 + n]))
	i += 3 + n

m = bytearray (65536)
m [0x4000:0x8000] = banks [5]
m [0x8000:0xc000] = banks [2]
m [0xc000:] = banks [p7 & 7]

def chan (a):
	o = []
	while m [a] != 0x40:
		o.append (m [a]); a += 1
	return o

# Check that the player is where we think
assert m [0xe985:0xe992] == bytes ([0x5e, 0x23, 0x56, 0x13, 0x1a, 0xfe, 0x40, 0x28, 0x12, 0x72, 0x2b, 0x73, 0xc9])
table = list (m [0xea35:0xea6b])
sweep = list (m [0xeb18:0xeb31])
c1, c2 = chan (0xeb31), chan (0xebb3)
tempo = m [0xe984]

def defbs (vals, ind = '\t\t'):
	return ''.join (ind + 'defb ' + ', '.join ('$%02x' % v for v in vals [i:i + 16]) + '\n' for i in range (0, len (vals), 16))

code = '''// MTE MK1 v3.2
// Copyleft 2011, 2026 by The Mojon Twins

// Nanako: the title tune of the original ZX version (2006), with its own two
// channel beeper player. Generated by tools/nanako_beeper.py from
// orig/ncjmc-zx.z80 (the player was at E979-EB30, the song at EB31-EC33).
//
// musicstart: from the start, until a key is pressed.
// musicresume: from where it was, until a key is pressed.
// Uses the ROM: BEEPER (03D4) and its bytes as noise (03E8).

#asm
	.musicstart
			ld  hl, nkm_ch1 - 1
			ld  (nkm_p1), hl
			ld  hl, nkm_ch1
			ld  (nkm_lp1), hl
			ld  hl, nkm_ch2 - 1
			ld  (nkm_p2), hl
			ld  hl, nkm_ch2
			ld  (nkm_lp2), hl

	.musicresume
			di
			call nkm_note
			ei
			xor a
			in  a, ($fe)
			or  $e0
			inc a
			jr  z, musicresume
			ret

	// Next byte of a channel. HL -> its pointer (then its loop pointer).
	// $40 = loop.
	.nkm_fetch
			ld  e, (hl)
			inc hl
			ld  d, (hl)
			inc de
	.nkm_f0
			ld  a, (de)
			cp  $40
			jr  z, nkm_floop
			ld  (hl), d
			dec hl
			ld  (hl), e
			ret
	.nkm_floop
			inc hl
			ld  e, (hl)
			inc hl
			ld  d, (hl)
			dec hl
			dec hl
			jr  nkm_f0

	// HL -> note: H = its counter (1 = silence), L = 1, E = note + 12
	.nkm_freq
			ld  a, (hl)
			add a, $0c
			ld  e, a
			ld  d, 0
			ld  hl, nkm_table
			add hl, de
			ld  h, (hl)
			ld  l, 1
			ret

	// One note of both channels
	.nkm_note
			ld  hl, nkm_p1
			call nkm_fetch
			ld  (nkm_n1), a
			ld  hl, nkm_p2
			call nkm_fetch
			ld  (nkm_n2), a
			ld  hl, nkm_n1
			call nkm_freq
			rl  e
			jp  c, nkm_special 		// Channel 1 >= $74: drums
			push hl
			ld  hl, nkm_n2
			call nkm_freq
			pop de
			ld  a, h
			dec a
			jr  nz, nkm_play
			ld  a, d
			dec a
			jr  z, nkm_rest

	.nkm_play
			ld  a, (nkm_tempo)
			ld  c, a
			ld  b, 0
			ld  a, (nkm_border)
			ex  af, af 		// af'
			ld  a, (nkm_border)
			defb $dd, $62 				// ld ixh, d
			ld  d, $10
	.nkm_l0
			nop
			nop
	.nkm_l1
			ex  af, af 		// af'
			dec e
			out ($fe), a
			jr  nz, nkm_l3
			defb $dd, $5c 				// ld e, ixh
			xor d
			ex  af, af 		// af'
			dec l
			jp  nz, nkm_l4
	.nkm_l2
			out ($fe), a
			ld  l, h
			xor d
			djnz nkm_l0
			inc c
			jp  nz, nkm_l1
			ret
	.nkm_l3
			jr  z, nkm_l3 				// Timing (never jumps)
			ex  af, af 		// af'
			dec l
			jp  z, nkm_l2
	.nkm_l4
			out ($fe), a
			nop
			nop
			djnz nkm_l0
			inc c
			jp  nz, nkm_l1
			ret

	.nkm_rest
			ld  a, (nkm_tempo)
			cpl
			ld  c, a
	.nkm_delay
			push bc
			push af
			ld  b, 0
	.nkm_d0
			push hl
			ld  hl, 0
			sra (hl)
			sra (hl)
			sra (hl)
			nop
			pop hl
			djnz nkm_d0
			dec c
			jp  nz, nkm_d0
			pop af
			pop bc
			ret

	// Drums: A = channel 1 + 12. $ff: noise, $c0: sweep, else bits 3-0 are
	// four steps (noise / silence). D = channel 2 (the noise pattern).
	.nkm_special
			push af
			ld  a, (nkm_n2)
			ld  d, a
			pop af
			call nkm_dur
			cp  $ff
			jr  z, nkm_noise
			cp  $c0
			jp  z, nkm_sweep
			ld  b, 4
			ld  c, e
			rla
			rla
			rla
			rla
	.nkm_s0
			rla
			call c, nkm_noise
			call nc, nkm_delay
			djnz nkm_s0
			ret

	.nkm_dur
			push af
			ld  a, (nkm_tempo)
			cpl
			ld  b, a
			ld  c, a
			add a, 1
			sra a
			sra a
			ld  e, a
			cp  0
			jr  nz, nkm_dur0
			inc e
	.nkm_dur0
			pop af
			ret

	.nkm_noise
			push af
			push hl
			push bc
			ld  a, (nkm_border)
			ld  b, 0
			ld  hl, $03e8
	.nkm_n0
			rrc d
			jp  nc, nkm_n3
			inc hl
			bit 0, (hl)
			jp  z, nkm_n2b
			set 4, a
	.nkm_nx
			xor $83
			xor $83
	.nkm_nout
			out ($fe), a
	.nkm_n1b
			nop
			dec b
			jp  nz, nkm_n0
			dec c
			jp  nz, nkm_n0
			pop bc
			pop hl
			pop af
			ret
	.nkm_n2b
			res 4, a
			jr  nkm_nout
	.nkm_n3
			scf
			jp  nc, 0 					// Timing (never jumps)
			jp  nc, 0
			jp  nc, 0
			nop
			nop
			jr  nkm_n1b

	.nkm_sweep
			ld  e, b
			ld  d, 0
			ld  hl, nkm_sweeptab
			adc hl, de
			ld  a, (hl)
			ld  b, a
			ld  hl, 3
	.nkm_w0
			push bc
			ld  de, 1
			push hl
			call nkm_beep
			pop hl
			ld  de, $ff
			adc hl, de
			pop bc
			djnz nkm_w0
			ret

	.nkm_beep
			ld  a, l
			srl l
			srl l
			cpl
			and 3
			ld  c, a
			ld  b, 0
			ld  ix, $03d1
			add ix, bc
			ld  a, (nkm_border)
			call $03d4
			di
			ret

'''
code += '''	// Variables
	.nkm_n1
			defb 0
	.nkm_n2
			defb 0
	.nkm_border
			defb 0
	.nkm_p1
			defw 0
	.nkm_lp1
			defw 0
	.nkm_p2
			defw 0
	.nkm_lp2
			defw 0
	.nkm_tempo
			defb $%02x

	// Counters per note (+ 12); 1 = silence
	.nkm_table
''' % tempo
code += defbs (table)
code += '\t.nkm_sweeptab\n' + defbs (sweep [:-1])
code += '\n\t// The song: %d notes per channel, $40 = loop\n\t\tdefb $%02x\n\t.nkm_ch1\n' % (len (c1), sweep [-1])
code += defbs (c1) + '\t\tdefb $40\n\t\tdefb 0\n\t.nkm_ch2\n' + defbs (c2) + '\t\tdefb $40\n#endasm\n'

open (os.path.join (D, 'dev', 'music.h'), 'w').write (code)
print ('music.h: %d + %d notes, tempo $%02x' % (len (c1), len (c2), tempo))
