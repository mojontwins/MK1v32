# Minimal BASIC tokenizer, enough for the one-line loaders of MK1.
TOKENS = {
	'RANDOMIZE': 0xF9, 'BORDER': 0xE7, 'PAPER': 0xDA, 'INK': 0xD9,
	'CLS': 0xFB, 'CLEAR': 0xFD, 'LOAD': 0xEF, 'SCREEN$': 0xAA,
	'POKE': 0xF4, 'CODE': 0xAF, 'USR': 0xC0, 'VAL': 0xB0, 'NOT': 0xC3,
	'PI': 0xA7, 'PRINT': 0xF5, 'GO TO': 0xEC, 'REM': 0xEA, 'BRIGHT': 0xDC,
}


def tokenize_line(text):
	num, rest = text.strip().split(' ', 1)
	out = bytearray()
	i = 0
	keys = sorted(TOKENS, key=len, reverse=True)
	while i < len(rest):
		c = rest[i]
		if c == '"':
			j = rest.index('"', i + 1)
			out += rest[i:j + 1].encode('ascii')
			i = j + 1
			continue
		for k in keys:
			if rest[i:i + len(k)].upper() == k:
				out.append(TOKENS[k])
				i += len(k)
				while i < len(rest) and rest[i] == ' ':
					i += 1
				break
		else:
			out.append(ord(c))
			i += 1
	out.append(13)
	n = int(num)
	return bytes([n >> 8, n & 255, len(out) & 255, len(out) >> 8]) + bytes(out)


def tap_block(flag, data):
	b = bytes([flag]) + data
	x = 0
	for v in b:
		x ^= v
	b += bytes([x])
	return bytes([len(b) & 255, len(b) >> 8]) + b


def tap_header(typ, name, length, p1, p2):
	nm = name[:10].ljust(10).encode('ascii')
	h = bytes([typ]) + nm + bytes([length & 255, length >> 8, p1 & 255, p1 >> 8, p2 & 255, p2 >> 8])
	return tap_block(0, h)


def mktap(args):
	out, name, bas = args[0], args[1], args[2]
	prog = b''.join(tokenize_line(l) for l in open(bas).read().splitlines() if l.strip())
	tap = tap_header(0, name, len(prog), 10, len(prog)) + tap_block(255, prog)
	for spec in args[3:]:
		fn, addr = spec.rsplit(':', 1)
		data = open(fn, 'rb').read()
		addr = int(addr)
		tap += tap_header(3, name, len(data), addr, 32768) + tap_block(255, data)
	open(out, 'wb').write(tap)
	print('mktap: %s (%d bytes)' % (out, len(tap)))


def printsize(args):
	n = len(open(args[0], 'rb').read())
	print('%s: %d bytes, ends at %d' % (args[0], n, 24200 + n))


if __name__ == '__main__':
	cmd, a = sys.argv[1], sys.argv[2:]
	{'rle53map': rle53map, 'ene2h': ene2h, 'mktap': mktap, 'printsize': printsize}[cmd](a)
