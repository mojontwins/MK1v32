#!/usr/bin/env python3
# Python ports of the MK1 v3.2 data converters.
#
#   mk1data.py rle53map in=mapa.map out=mapa.bin size=W,H [scrsize=15,10]
#              [tlock=15] [mk1locks] [mk1h=mapa.h] [fixmappy] [nodecos]
#                                                  (= rle53map_sp.exe)
#   mk1data.py ene2h enems.ene enems.h [2bytes] [compacted] [indexed]
#                                                  (= ene2h.exe)
#   mk1data.py mktap out.tap name loader.bas screen.bin:32768 game.bin:24200
#                                    (= bas2tap.exe + bin2tap.exe)
#   mk1data.py printsize game.bin
#
# Output follows the FreeBASIC originals in utils/*.bas.

import sys


def kv(args):
	d = {}
	for a in args:
		if '=' in a:
			k, v = a.split('=', 1)
			d[k.lower()] = v
		else:
			d[a.lower()] = '1'
	return d


# ------------------------------------------------------------- rle53map ---

def rle53map(args):
	o = kv(args)
	mapW, mapH = [int(v) for v in o['size'].split(',')]
	scrW, scrH = [int(v) for v in o.get('scrsize', '15,10').split(',')]
	tlock = int(o['tlock']) if 'tlock' in o else -1
	t0 = int(o.get('t0', '0'))
	mk1locks = 'mk1locks' in o
	fixmappy = 'fixmappy' in o
	nodecos = 'nodecos' in o
	base = o['out']
	if '.bin' in base:
		base = base[:base.index('.bin')]
	data = open(o['in'], 'rb').read()
	mapWt = mapW * scrW
	maxp = mapW * mapH
	big = [[0] * (scrW * scrH) for _ in range(maxp)]
	locks = []
	decos = [[] for _ in range(maxp)]
	dp = 0
	oor = False
	for i, d in enumerate(data):
		if fixmappy and d:
			d -= 1
		xp = (i // scrW) % mapW
		yp = i // (scrW * scrH * mapW)
		x = i % scrW
		y = (i // mapWt) % scrH
		np_ = xp + yp * mapW
		if np_ >= maxp:
			break
		if d == tlock:
			if mk1locks:
				locks += [np_, x, y, 0]
			else:
				locks += [np_, (y << 4) | x]
		if d < t0 or d > t0 + 31:
			oor = True
			decos[np_].append((y * 16 + x, d))
			d = dp
		big[np_][scrW * y + x] = d - t0
		dp = d
	if oor:
		print('rle53map: WARNING tiles out of range 0-31 (%s)' % ('ignored' if nodecos else 'decos'))
	cmaps = []
	amalg = []
	real = []
	for n in range(maxp):
		scr = big[n]
		cm = []
		d = scr[0]; cnt = 1
		ssum = 0
		for i in range(1, scrW * scrH):
			ssum += scr[i]
			if scr[i] != d or cnt == 8:
				cm.append((d & 31) | ((cnt - 1) << 5))
				cnt = 0
			d = scr[i]; cnt += 1
		cm.append((d & 31) | ((cnt - 1) << 5))
		a = bytes(cm)
		rp = n
		if ssum == 0:
			rp = 255; cm = []
		else:
			for j in range(n):
				if amalg[j] == a:
					rp = j; cm = []
					break
		amalg.append(a)
		cmaps.append(cm)
		real.append(rp)
	out = bytearray(2 * maxp)
	offs = [0] * maxp
	for n in range(maxp):
		if real[n] == 255:
			pass
		elif cmaps[n]:
			out[n * 2] = len(out) & 255
			out[n * 2 + 1] = len(out) >> 8
			offs[n] = len(out)
			out += bytes(cmaps[n])
		else:
			out[n * 2] = offs[real[n]] & 255
			out[n * 2 + 1] = offs[real[n]] >> 8
	open(base + '.map.bin', 'wb').write(out)
	if locks:
		open(base + '.locks.bin', 'wb').write(bytes(locks))
	if 'mk1h' in o:
		h = []
		h.append('// Mapa.h ')
		h.append('// Generated by rle53map (Python port of rle53map_sp v0.2.20200214)')
		h.append('// Copyleft 2020 by The Mojon Twins')
		h.append('')
		h.append('extern unsigned char mapa [0];')
		h.append('')
		h.append('#asm')
		h.append('    ._mapa')
		h.append('        BINARY "%s.map.bin"' % base)
		h.append('#endasm')
		h.append('')
		h.append('#define MAX_CERROJOS %d' % (len(locks) // 4))
		h.append('')
		h.append('typedef struct {')
		h.append('    unsigned char np, x, y, st;')
		h.append('} CERROJOS;')
		h.append('')
		h.append('extern CERROJOS cerrojos [0];')
		h.append('')
		h.append('#asm')
		h.append('    ._cerrojos')
		h.append('    #if MAX_CERROJOS > 0')
		h.append('        BINARY "%s.locks.bin"' % base)
		h.append('    #endif')
		h.append('#endasm')
		h.append('')
		open(o['mk1h'], 'w').write('\n'.join(h) + '\n')
	print('rle53map: M=%d L=%d' % (len(out), len(locks)))


# ---------------------------------------------------------------- ene2h ---

def ene2h(args):
	fin, fout = args[0], args[1]
	flags = set(a.lower() for a in args[2:])
	use2 = '2bytes' in flags
	compacted = 'compacted' in flags
	indexed = 'indexed' in flags
	d = open(fin, 'rb').read()
	mapW, mapH, nE = d[256], d[257], d[260]
	p = 261
	mp = mapW * mapH
	o = []
	o.append('// MTE MK1 (la Churrera) v4')
	o.append('// Copyleft 2010-2014, 2020-2025 by the Mojon Twins')
	o.append('')
	o.append('// Generated by ene2h (Python port) from ' + fin)
	o.append('// Copyleft 2010, 2017, 2020-2025 by The Mojon Twins')
	o.append('')
	o.append('typedef struct {')
	o.append('\tunsigned char x, y;')
	o.append('\tunsigned char xy1, xy2;' if compacted else '\tunsigned char x1, y1, x2, y2;')
	o.append('\tsigned char mx, my;')
	o.append('\tsigned char t;')
	o.append('#if ((defined PLAYER_CAN_FIRE || defined ENABLE_SWORD) && ENEMS_LIFE_GAUGE > 1) || defined FORCE_ENEMS_LIFE')
	o.append('\tunsigned char life;')
	o.append('#endif')
	o.append('} MALOTE;')
	o.append('')
	o.append('MALOTE malotes [] = {')
	encnt = [0] * 256
	index = []
	nonempty = 0
	sgn = lambda v: (v > 0) - (v < 0)
	for i in range(mp):
		o.append('\t// Pantalla %d' % i)
		index.append(nonempty)
		for j in range(nE):
			t, x, y, xx, yy, mn, s1, s2 = d[p:p + 8]
			p += 8
			outX, outY = 16 * x, 16 * y
			encnt[t] += 1
			sx, sy = sgn(xx - x), sgn(yy - y)
			if x > xx: x, xx = xx, x
			if y > yy: y, yy = yy, y
			x1, y1, x2, y2 = 16 * x, 16 * y, 16 * xx, 16 * yy
			mx, my = mn * sx, mn * sy
			if not indexed or t != 0:
				line = ' \t{%d, %d, ' % (outX, outY)
				if compacted:
					line += '0x%02X, 0x%02X, ' % (x1 + y1 // 16, x2 + y2 // 16)
				else:
					line += '%d, %d, %d, %d, ' % (x1, y1, x2, y2)
				line += '%d, %d, %d}' % (mx, my, t)
				if i < mp - 1 or j < nE - 1:
					line += ','
				o.append(line)
				nonempty += 1
		o.append('')
	if indexed and nonempty < mp * nE:
		o.append('\t{0xff}')
	o.append('};')
	o.append('')
	if indexed:
		o.append('// enoffs index, contains enoffs for each screen')
		o.append('unsigned char enoffs_index [] = {')
		k = 0
		for j in range(mapH):
			o.append('\t' + ''.join('%d, ' % index[k + i] for i in range(mapW)))
			k += mapW
		o.append('\t%d // <- total number of enems to make coding easier' % nonempty)
		o.append('};')
		o.append('')
	for i in range(256):
		if (encnt[i] > 0 or i <= 7) and i != 4:
			o.append('#define N_ENEMS_TYPE_%d %d' % (i, encnt[i]))
	o.append('')
	o.append('#define BADDIES_COUNT (N_ENEMS_TYPE_1+N_ENEMS_TYPE_2+N_ENEMS_TYPE_3)')
	o.append('')
	o.append('#define TOTAL_EXISTING_ENEMS %d' % (nonempty if indexed else mp * nE))
	o.append('')
	o.append('typedef struct {')
	o.append('\tunsigned char xy, tipo, act;')
	o.append('} HOTSPOT;')
	o.append('')
	o.append('HOTSPOT hotspots [] = {')
	hcnt = [0] * 256
	for i in range(mp):
		if use2:
			xy, t = d[p], d[p + 1]; p += 2
		else:
			x, y, t = d[p], d[p + 1], d[p + 2]; p += 3
			xy = ((x << 4) | (y & 15)) & 255
		hcnt[t] += 1
		o.append('\t{%d, %d, 0}%s' % (xy, t, ', ' if i < mp - 1 else ''))
	o.append('};')
	o.append('')
	for i in range(256):
		if hcnt[i] or i < 8:
			o.append('#define N_HOTSPOTS_TYPE_%d %d' % (i, hcnt[i]))
	o.append('')
	open(fout, 'w').write('\n'.join(o) + '\n')
	print('ene2h: %d enemies' % nonempty)


