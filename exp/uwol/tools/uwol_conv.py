# uwol_conv.py - one-shot conversion of the original Uwol (2009) data to MK1 v3.2
#
# usage: python3 uwol_conv.py          (paths are relative to this script's folder)
#
# Reads ../orig and writes:
#   ../dev/rooms.h               55 rooms for the custom map renderer
#   ../enems/enems.ene           enemies (linear) for ene2h, 55 rooms x 3
#   ../gfx/speccy/sprites.png    25 cells: clothed 0-7, naked 8-15, enemies 16-23, dead 24
#   ../gfx/speccy/font.png       from gfx/fuente.png
#   ../gfx/speccy/title.png      original title without the controls text
#   ../gfx/speccy/ending.png     good ending drawing without its text
#   ../gfx/speccy/marco.png      the HUD frame
#   ../gfx/speccy/loading.png    from gfx/scr/loading.bin
#
# work.png (the tileset) is hand made: gfx/speccy/work.png.

import os, re, sys
from PIL import Image

H = os.path.dirname (os.path.abspath (__file__))
O = os.path.join (H, '..', 'orig')
D = os.path.join (H, '..')

def rd (*p):
	return open (os.path.join (O, *p), 'rb').read ().decode ('latin-1').replace ('\r', '')

def out (*p):
	f = os.path.join (D, *p)
	os.makedirs (os.path.dirname (f), exist_ok = True)
	return f

# ----------------------------------------------------------------------------
# Rooms
# ----------------------------------------------------------------------------

t = rd ('dev', 'fases.h')
seg = t [t.index ('._fases'):]
src = re.split (r';\.Pantalla \d+', seg) [1:]
assert len (src) == 45

def pyramid_level (r):
	# Level (1-10) of room r: row l holds l rooms
	l = 1
	while r >= l:
		r -= l
		l += 1
	return l

rooms = []
for k in range (45):
	b = [int (x, 2) for x in re.findall (r'@([01]{8})', src [k])]
	assert len (b) == 37
	rooms.append ({
		'desc': b [0],
		'objs': [w for w in (b [1 + 2 * i] | (b [2 + 2 * i] << 8) for i in range (10)) if w],
		'movs': [b [21 + 2 * i] | (b [22 + 2 * i] << 8) for i in range (3)],
		'coins': [c for c in b [27:37] if c]
	})

# Rooms 45-54 are physically duplicated from 0-9 (the original used n_pant % 45).
# Different colours and platform types so they don't look the same.
for k in range (10):
	r = rooms [k]
	objs = []
	for w in r ['objs']:
		n = ((w >> 1) & 7) ^ 4 						# other platform type
		objs.append ((w & 0xfff1) | (n << 1))
	ink, pap = r ['desc'] & 7, (r ['desc'] >> 3) & 7
	if ink < pap: ink, pap = pap, ink
	ink = ink + 1 if ink < 7 else 2 				# other ink
	if ink == pap: ink = 7
	rooms.append ({'desc': ink | (pap << 3), 'objs': objs, 'movs': r ['movs'], 'coins': r ['coins']})

def room_attr (k):
	a = rooms [k]['desc'] & 63
	ink, pap = a & 7, a >> 3
	if ink < pap: ink, pap = pap, ink
	return ink | (pap << 3)

# rooms.h: index (2 bytes each) + per room:
#   attr  (ZX attribute for the background: INK > PAPER)
#   n_objs, then 2 bytes per object: XXXXYYYY, LLLLTTTD
#   n_coins, then 1 byte per coin: XXXXYYYY
# Coordinates are in playfield tiles (0-11, 0-9); the map is shifted 1 column.

data = []
index = []
for k in range (55):
	r = rooms [k]
	index.append (len (data))
	data.append (room_attr (k))
	data.append (len (r ['objs']))
	for w in r ['objs']:
		data += [w >> 8, w & 255]
	data.append (len (r ['coins']))
	data += r ['coins']

with open (out ('dev', 'rooms.h'), 'w') as f:
	f.write ('// Uwol rooms, generated by tools/uwol_conv.py from the original fases.h\n')
	f.write ('// Per room: attr, n_objs, n_objs * (XXXXYYYY, LLLLTTTD), n_coins, n_coins * XXXXYYYY\n\n')
	f.write ('extern unsigned char rooms_index [];\n')
	f.write ('extern unsigned char rooms_data [];\n\n')
	f.write ('#asm\n')
	f.write ('\t._rooms_index\n')
	for i in range (0, 55, 8):
		f.write ('\t\t\tdefw ' + ', '.join ('_rooms_data + %d' % v for v in index [i:i + 8]) + '\n')
	f.write ('\t._rooms_data\n')
	for k in range (55):
		a, b = index [k], index [k + 1] if k < 54 else len (data)
		f.write ('\t\t\tdefb ' + ', '.join (str (v) for v in data [a:b]) + '\t\t// %d\n' % k)
	f.write ('#endasm\n')

print ('rooms.h: %d bytes' % (len (data) + 110))

# ----------------------------------------------------------------------------
# Enemies -> ponedor .ene (55 x 1 screens of 15 x 10, 3 enemies per screen)
# Original: AAAABBBBYYYYRTTV. Type 0 wolfy, 1 franky, 2 vampy; MK1 types 1-3.
# Starts at the left limit moving right at 1 or 2 pixels per frame.
# ----------------------------------------------------------------------------

ene = bytearray ()
for k in range (55):
	for m in rooms [k]['movs']:
		if m == 0:
			ene += bytes (8)
			continue
		a, b, y, ty, v = (m >> 12) & 15, (m >> 8) & 15, (m >> 4) & 15, (m >> 1) & 3, m & 1
		assert ty < 3
		ene += bytes ([ty + 1, a + 1, y, b + 1, y, v + 1, 0, 0])
for k in range (55):
	ene += bytes (2) 							# no hotspots
hdr = bytearray (256)
tag = b'Uwol, Quest for Money (from the original fases.h)'
hdr [:len (tag)] = tag
open (out ('enems', 'enems.ene'), 'wb').write (bytes (hdr) + bytes ([55, 1, 15, 10, 3]) + bytes (ene))

# ----------------------------------------------------------------------------
# Sprites (from the original sprites.h, splib2 masked columns)
# ----------------------------------------------------------------------------

s = rd ('dev', 'sprites.h')
s = s [s.index ('#asm'):]
parts = re.split (r'\n\._(\w+)', s)
spr = {}
for k in range (1, len (parts), 2):
	rows = re.findall (r'defb\s*@([01]{8})\s*,\s*@([01]{8})', parts [k + 1])
	spr [parts [k]] = [(int (g, 2), int (m, 2)) for g, m in rows [:16]]

S = Image.new ('RGB', (256, 64), (0, 0, 0))
def cell (n, name):
	x0, y0 = (n & 7) * 32, (n >> 3) * 16
	for col, suf in enumerate ('ab'):
		for r, (g, m) in enumerate (spr [name + suf]):
			for p in range (8):
				x = col * 8 + p
				S.putpixel ((x0 + x, y0 + r), (255, 255, 255) if g & (128 >> p) else (0, 0, 0))
				S.putpixel ((x0 + 16 + x, y0 + r), (255, 0, 0) if m & (128 >> p) else (0, 0, 0))
for i in range (25, 32):
	x0, y0 = (i & 7) * 32, (i >> 3) * 16
	S.paste ((255, 0, 0), (x0 + 16, y0, x0 + 32, y0 + 16))

# MK1 sideview: right 0-3, left 4-7; walk 0,1,2,1; still 1; jump 3.
for row, pre in enumerate (['uwol', 'uwolpelot']):
	for j, (d, f) in enumerate ([('r', 1), ('r', 2), ('r', 3), ('r', 3), ('l', 1), ('l', 2), ('l', 3), ('l', 3)]):
		cell (row * 8 + j, '%s_%s_%d' % (pre, d, f))
for i, e in enumerate (['wolfi_1', 'franki_1', 'vampi_1']):
	cell (16 + i * 2, e)
	cell (17 + i * 2, e)
cell (22, 'fanti_r_1')
cell (23, 'fanti_l_1')
cell (24, 'uwolmuete_1')
S.save (out ('gfx', 'speccy', 'sprites.png'))

