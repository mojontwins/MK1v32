def img (*p):
	return Image.open (os.path.join (O, *p)).convert ('RGB')

def blank_rows (im, c0, c1):
	# Black out character rows c0..c1 (inclusive)
	im.paste ((0, 0, 0), (0, c0 * 8, 256, (c1 + 1) * 8))
	return im

# Font: the first two rows of fuente.png are ASCII 32-95.
img ('gfx', 'fuente.png').crop ((0, 0, 256, 16)).save (out ('gfx', 'speccy', 'font.png'))

# Title: the controls text (rows 21-22) goes, the game prints its own.
blank_rows (img ('gfx', 'title.png'), 20, 23).save (out ('gfx', 'speccy', 'title.png'))

# Ending: the good ending drawing, text printed by the game.
blank_rows (img ('gfx', 'fin-good.png'), 15, 23).save (out ('gfx', 'speccy', 'ending.png'))

# Loading screen from the original .scr
def scr2png (data):
	im = Image.new ('RGB', (256, 192))
	pal = [(0, 0, 0), (0, 0, 200), (200, 0, 0), (200, 0, 200), (0, 200, 0), (0, 200, 200), (200, 200, 0), (200, 200, 200)]
	for y in range (192):
		a = ((y & 0xc0) << 5) | ((y & 7) << 8) | ((y & 0x38) << 2)
		for cx in range (32):
			b = data [a + cx]
			at = data [6144 + (y >> 3) * 32 + cx]
			br = 55 if at & 64 else 0
			ink = tuple (min (255, v + br) if v else 0 for v in pal [at & 7])
			pap = tuple (min (255, v + br) if v else 0 for v in pal [(at >> 3) & 7])
			for p in range (8):
				im.putpixel ((cx * 8 + p, y), ink if b & (128 >> p) else pap)
	return im

scr2png (open (os.path.join (O, 'gfx', 'scr', 'loading.bin'), 'rb').read () [:6912]).save (out ('gfx', 'speccy', 'loading.png'))

# HUD frame: icons from the tileset, labels with the font.
W = Image.open (os.path.join (D, 'gfx', 'speccy', 'work.png')).convert ('RGB')
F = Image.open (out ('gfx', 'speccy', 'font.png')).convert ('RGB')
M = Image.new ('RGB', (256, 192), (0, 0, 0))

def tile (n, cx, cy):
	M.paste (W.crop (((n & 15) * 16, (n >> 4) * 16, (n & 15) * 16 + 16, (n >> 4) * 16 + 16)), (cx * 8, cy * 8))

def text (s, cx, cy, col):
	for i, ch in enumerate (s):
		c = ord (ch) - 32
		g = F.crop (((c & 31) * 8, (c >> 5) * 8, (c & 31) * 8 + 8, (c >> 5) * 8 + 8))
		for y in range (8):
			for x in range (8):
				if g.getpixel ((x, y)) != (0, 0, 0):
					M.putpixel (((cx + i) * 8 + x, cy * 8 + y), col)

tile (25, 4, 0) 								# Uwol's face, lives at (6,1)
text ('X', 6, 1, (255, 255, 255))
text ('TIME', 12, 1, (0, 255, 0))
text ('X', 16, 1, (255, 255, 255))
tile (26, 22, 0) 								# coin, coins at (24,1)
text ('X', 24, 1, (255, 255, 255))
text ('LEVEL', 4, 23, (0, 200, 0))
text ('X', 9, 23, (200, 200, 200))
text ('SCORE', 17, 23, (0, 200, 0))
text ('X', 22, 23, (200, 200, 200))
M.save (out ('gfx', 'speccy', 'marco.png'))

print ('ok')

# ----------------------------------------------------------------------------
# CPC (mode 0, 16 colours) placeholders made from the ZX graphics. Half width:
# a mode 0 pixel is two ZX pixels wide (the ink one of a pair wins).
# Pens 1 and 2 are each room's background paper and ink (set at run time);
# the background, shaded background and coin tiles use only them.
# ----------------------------------------------------------------------------

PAL = [(255, 128, 255), 				# 0  transparent (sprites)
	(0, 0, 128), (128, 0, 255), 		# 1, 2  room paper, room ink (placeholders)
	(0, 0, 0), 							# 3  black
	(0, 0, 255), (255, 0, 0), (255, 0, 255), (0, 255, 0), (0, 255, 255), (255, 255, 0), (255, 255, 255),
										# 4-10 bright blue, red, magenta, green, cyan, yellow, white
	(128, 0, 0), (128, 128, 0), (0, 128, 128), (128, 128, 128), (0, 128, 0)]
										# 11-15 red, yellow, cyan, white, green

def zxk (c):
	# ZX colour number (0-7) and brightness of an RGB pixel
	r, g, b = c
	k = (1 if b > 64 else 0) | (2 if r > 64 else 0) | (4 if g > 64 else 0)
	return k, max (c) > 230

def zxcpc (c):
	k, br = zxk (c)
	if k == 0: return PAL [3]
	if br: return PAL [[0, 4, 5, 6, 7, 8, 9, 10] [k]]
	return PAL [[0, 4, 11, 6, 15, 13, 12, 14] [k]]

def half (im, conv = zxcpc):
	w, h = im.size
	o = Image.new ('RGB', (w // 2, h))
	src = im.load (); dst = o.load ()
	for y in range (h):
		for x in range (0, w - 1, 2):
			a, b = conv (src [x, y]), conv (src [x + 1, y])
			dst [x // 2, y] = b if a in (PAL [3], PAL [1]) else a
	return o

C = os.path.join ('gfx', 'cpc')
pal = Image.new ('RGB', (16, 1))
pal.putdata (PAL)
pal.save (out (C, 'pal.png'))

# Tileset: the room-coloured tiles go to pens 1 (paper, lower ZX colour) and 2 (ink).
W = Image.open (os.path.join (D, 'gfx', 'speccy', 'work.png')).convert ('RGB')
Wc = half (W)
for t in list (range (0, 4)) + list (range (12, 16)) + list (range (32, 36)):
	x0, y0 = (t & 15) * 16, (t >> 4) * 16
	tile = W.crop ((x0, y0, x0 + 16, y0 + 16))
	ks = sorted (set (zxk (c) [0] for c in tile.getdata ()))
	ink = ks [-1]
	def conv (c, ink = ink):
		return PAL [2] if zxk (c) [0] == ink and len (ks) > 1 else PAL [1]
	Wc.paste (half (tile, conv), (x0 // 2, y0))
Wc.save (out (C, 'work.png'))

half (Image.open (out ('gfx', 'speccy', 'font.png')).convert ('RGB')).save (out (C, 'font.png'))
for s in ('title', 'ending', 'marco'):
	half (Image.open (out ('gfx', 'speccy', s + '.png')).convert ('RGB')).save (out (C, s + '.png'))
ld = Image.new ('RGB', (160, 200), PAL [3])
ld.paste (half (Image.open (out ('gfx', 'speccy', 'loading.png')).convert ('RGB')), (16, 4))
ld.save (out (C, 'loading.png'))
pal.save (out (C, 'pal_loading.png'))

# Sprites: 25 cells of 8 x 16, 8 a row. One colour per sprite, black outline
# from the mask, pen 0 transparent.
cols = [PAL [10]] * 16 + [PAL [8]] * 2 + [PAL [7]] * 2 + [PAL [6]] * 2 + [PAL [10]] * 2 + [PAL [10]]
Sz = Image.open (out ('gfx', 'speccy', 'sprites.png')).convert ('RGB')
o = Image.new ('RGB', (64, 64), PAL [0])
for n in range (25):
	fx, fy = (n % 8) * 32, (n // 8) * 16
	for y in range (16):
		for x in range (8):
			px = [Sz.getpixel ((fx + 2 * x + k, fy + y)) != (0, 0, 0) for k in (0, 1)]
			mk = [Sz.getpixel ((fx + 16 + 2 * x + k, fy + y)) != (0, 0, 0) for k in (0, 1)]
			if any (px): c = cols [n]
			elif not all (mk): c = PAL [3]
			else: c = PAL [0]
			o.putpixel (((n % 8) * 8 + x, (n // 8) * 16 + y), c)
o.save (out (C, 'sprites.png'))

# Extra sprite (MK1's explosion, unused by Uwol but needed by ENEMIES_MAY_DIE)
